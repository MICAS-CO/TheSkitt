function substSkin(rows: string[], map: Record<string, string>): string[] {
  return rows.map((row) => {
    let out = "";
    for (let i = 0; i < row.length; i++) {
      out += map[row[i]!] ?? row[i];
    }
    return out;
  });
}

function applyDiffs(rows: string[], diffs: SpriteDiff[]): string[] {
  const grid = rows.map((r) => r.split(""));
  for (const d of diffs) {
    if (grid[d.row] && d.col < grid[d.row]!.length) {
      grid[d.row]![d.col] = d.ch;
    }
  }
  return grid.map((r) => r.join(""));
}

export function dropPatientFrames(patientId: string, state: string): string[][] | null {
  const bp = DROP_PATIENT_SPRITES[patientId];
  if (!bp) return null;
  // Stable is the base upright + exhale
  if (state === "stable" || state === "unseen" || state === "discharged") {
    return [bp.upright, bp.exhale];
  }
  const stateKey = state === "post_resus" || state === "admitted" ? "postResus" : state === "deceased" ? "arrested" : state;
  const recipe = bp.states[stateKey];
  if (!recipe) return null;
  const baseInhale = recipe.base === "supine" ? bp.supine : bp.upright;
  const baseExhale = recipe.base === "supine" ? bp.supine : bp.exhale;
  const tinted1 = recipe.skinMap ? substSkin(baseInhale, recipe.skinMap) : baseInhale;
  const tinted2 = recipe.skinMap ? substSkin(baseExhale, recipe.skinMap) : baseExhale;
  const f1 = recipe.diffs ? applyDiffs(tinted1, recipe.diffs) : tinted1;
  const f2 = recipe.diffs ? applyDiffs(tinted2, recipe.diffs) : tinted2;
  // Supine states are single-frame (no exhale variant needed)
  return recipe.base === "supine" ? [f1] : [f1, f2];
}

export function dropFrameToSvg(rows: string[], scale = 6): string {
  const w = rows[0]!.length;
  const h = rows.length;
  let svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" ` +
    `shape-rendering="crispEdges" style="image-rendering:pixelated;` +
    `width:${w * scale}px;height:${h * scale}px;display:block">`;
  for (let y = 0; y < h; y++) {
    const row = rows[y]!;
    let x = 0;
    while (x < row.length) {
      const ch = row[x]!;
      const col = DROP_PAL[ch];
      if (col == null) {
        x++;
        continue;
      }
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      svg += `<rect x="${x}" y="${y}" width="${end - x}" height="1" fill="${col}"/>`;
      x = end;
    }
  }
  svg += "</svg>";
  return svg;
}