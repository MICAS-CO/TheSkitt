/**
 * Drop #3 patient sprites — FULL state machinery (M75).
 *
 * 13 character archetypes ported with their 5 states (stable +
 * triaged + deteriorating + arrested + post-resus). Self-contained
 * PAL + renderer so chars do not collide with sprites.ts (Williams
 * M44 uses E/J/K/y differently; M72 uses 0-9 for Stan/Patel/Chloe
 * clothing; the drop uses 1-9/E/J/K/x/y/z for these patients).
 *
 * Wired into PATIENT_SPRITES via the per-case map in sprites.ts.
 */

export interface SpriteDiff {
  row: number;
  col: number;
  ch: string;
}

export interface PatientStateRecipe {
  /** Which base frame the state recipe operates on. */
  base: "upright" | "supine";
  /** Optional skin-tint substitution map applied before diffs. */
  skinMap?: Record<string, string>;
  /** Per-cell overrides applied on top of the (possibly substituted) base. */
  diffs?: SpriteDiff[];
}

export interface PatientSpriteBlueprint {
  upright: string[];
  exhale: string[];
  supine: string[];
  states: Record<string, PatientStateRecipe>;
}

